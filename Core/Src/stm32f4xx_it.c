/**
  ******************************************************************************
  * @file    stm32f4xx_it.c
  * @brief   中断服务程序
  *
  *  SysTick  1kHz：毫秒时基 + 舵机速度规划
  *  USART1        ：串口收发
  ******************************************************************************
  */
#include "config.h"
#include "board.h"
#include "uart.h"
#include "servo.h"

/*----------------------------------------------------------------------------
 * 系统节拍：1kHz
 *--------------------------------------------------------------------------*/
void SysTick_Handler(void)
{
    board_tick_1ms();
    servo_tick_1ms();
}

/*----------------------------------------------------------------------------
 * 串口：中断向量名由 config.h 的 BOARD_UART_IRQ_HANDLER 决定
 *--------------------------------------------------------------------------*/
void BOARD_UART_IRQ_HANDLER(void)
{
    uart_irq_handler();
}

/*----------------------------------------------------------------------------
 * 硬件错误：停在这里，方便调试器直接看到现场
 *--------------------------------------------------------------------------*/
void HardFault_Handler(void)
{
    for (;;) {
    }
}
